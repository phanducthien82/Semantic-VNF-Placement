"""Generate every figure, table and number of the revised manuscript from the raw results.

Outputs (paths relative to the LaTeX folder given by --tex):
  figs/*.pdf            figures
  tables/*.tex          table bodies (tabular environments)
  results_macros.tex    \\R{key} values used in the text
  ../../Code/.../results/summary/*.csv  per-run summaries and statistical tests

Every number in the paper therefore comes from results/*/runs.jsonl.
"""
